'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { Workbench, git } = require('../core.cjs');
const { createServer } = require('../server.cjs');
async function main() {
  const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'workbench-ui-'));
  const repo = path.join(root, 'repo with spaces'); fs.mkdirSync(repo);
  await git(repo, ['init']); await git(repo, ['config', 'user.name', 'UI Test']); await git(repo, ['config', 'user.email', 'ui@localhost']);
  fs.writeFileSync(path.join(repo, 'README.md'), '# UI test'); await git(repo, ['add', '.']); await git(repo, ['-c', 'commit.gpgsign=false', 'commit', '-m', 'fixture']);
  const wb = new Workbench(path.join(root, 'data'), { providers: { codex: { executable: process.execPath }, claude: { executable: process.execPath } }, command: (_t, _e, out) => ({ executable: process.execPath, args: [path.join(__dirname, 'fake-cli.cjs'), out] }) });
  const { server, token } = createServer(wb); await new Promise(r => server.listen(0, '127.0.0.1', r));
  let browser;
  try {
    browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
    const page = await browser.newPage({ viewport: { width: 1560, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(`http://127.0.0.1:${server.address().port}/#${token}`);
    await page.getByRole('button', { name: '添加本机项目', exact: true }).click();
    await page.locator('#project-form [name=name]').fill('示例项目 · 协作验证');
    await page.locator('#project-form [name=path]').fill(repo);
    await page.locator('#project-form').getByRole('button', { name: '添加项目', exact: true }).click();
    await page.getByRole('heading', { name: '示例项目 · 协作验证', exact: true }).waitFor();
    await page.locator('#shared').click();
    await page.locator('#context-form [name=context]').fill('用户手动分工。地图客户端与服务端分别实现，由用户验收后交接。');
    await page.locator('#context-form [name=contracts]').fill('GET /mapdata：接口字段由双方确认后记录在此处。');
    await page.getByRole('button', { name: '保存新版本' }).click();
    await page.locator('#new-task').click();
    await page.locator('#task-form [name=autoContinue]').uncheck();
    await page.locator('#task-form [name=autoStart]').uncheck();
    await page.locator('#task-form [name=title]').fill('实现地图 UI <script>alert(1)</script>');
    await page.locator('#task-form [name=scope]').fill('world/game/');
    await page.locator('#task-form [name=prompt]').fill('实现圆形小地图，记录接口依赖和验证结果。');
    await page.getByRole('button', { name: '保存分工' }).click();
    await page.getByRole('button', { name: '查看完整输入' }).click();
    await page.waitForFunction(() => document.querySelector('#prompt-content')?.textContent.includes('GET /mapdata'));
    assert.match(await page.locator('#prompt-content').textContent(), /GET \/mapdata/);
    await page.locator('#prompt-dialog [data-close]').click();
    await page.getByRole('button', { name: '开始执行', exact: true }).click();
    await page.getByRole('button', { name: '验收完成', exact: true }).waitFor({ timeout: 20000 });
    assert.ok(await page.locator('.result').textContent());
    await page.getByRole('button', { name: '交接给另一方' }).click();
    await page.locator('#task-form [name=autoContinue]').uncheck();
    await page.locator('#task-form [name=autoStart]').uncheck();
    await page.getByRole('button', { name: '保存分工' }).click();
    await page.getByRole('button', { name: '开始执行', exact: true }).click();
    await page.getByRole('button', { name: '验收完成', exact: true }).waitFor({ timeout: 20000 });
    assert.equal(wb.state.tasks[0].provider, 'claude');
    assert.equal(wb.state.tasks[0].workspace, wb.state.tasks[1].workspace);
    await page.getByRole('button', { name: '验收完成', exact: true }).click();
    await page.locator('#detail [data-action=close]').click();
    await page.locator('#new-task').click();
    await page.locator('#task-form [name=autoContinue]').uncheck();
    await page.locator('#task-form [name=autoStart]').uncheck();
    await page.locator('#task-form [name=title]').fill('补充地图服务接口');
    await page.locator('#task-form [name=provider]').selectOption('claude');
    await page.locator('#task-form [name=prompt]').fill('提供地图数据与地点列表，填写共享接口约定。');
    await page.getByRole('button', { name: '保存分工' }).click();
    await page.locator('#detail [data-action=close]').click();
    await page.locator('#new-task').click();
    assert.equal(await page.locator('#task-form [name=autoContinue]').isChecked(), true);
    assert.equal(await page.locator('#task-form [name=autoStart]').isChecked(), true);
    await page.locator('#task-form [name=title]').fill('relay-stage-1');
    await page.locator('#task-form [name=provider]').selectOption('codex');
    await page.locator('#task-form [name=prompt]').fill('自动接力，直到第四步完成。');
    await page.getByRole('button', { name: '保存分工' }).click();
    // No start, approve, handoff, or refresh clicks from here onward.
    await page.waitForFunction(() => document.querySelector('#workflows')?.textContent.includes('整组任务全部完成'), null, { timeout: 30000 });
    const flow = wb.state.workflows[0];
    assert.equal(flow.status, 'completed');
    assert.equal(wb.state.tasks.filter(t => t.workflowId === flow.id).length, 4);
    await page.locator('#detail [data-action=close]').click();
    await page.screenshot({ path: path.join(__dirname, '..', 'ui-validation.png'), fullPage: true });
    assert.deepEqual(errors, []); console.log('UI_SMOKE PASS: manual regression + default automatic four-turn relay + XSS-safe-render');
  } finally { if (browser) await browser.close(); await wb.close(); server.closeAllConnections(); await new Promise(r => server.close(r)); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
